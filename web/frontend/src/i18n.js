function getByPath(obj, path) {
  return path.split('.').reduce((acc, k) => (acc && acc[k] !== undefined ? acc[k] : undefined), obj)
}

export function langCodeFromProfile(lang) {
  if (lang === 'Nasa Yuwe') return 'ny'
  if (lang === 'Bilingue') return 'bi'
  return 'es'
}

/**
 * @param {string} profileLanguage - "Espanol" | "Nasa Yuwe" | "Bilingue"
 */
export function createTranslator(profileLanguage) {
  const code = langCodeFromProfile(profileLanguage)
  const es = STRINGS.es
  const ny = STRINGS.ny

  return function t(path, params = {}) {
    const esVal = getByPath(es, path)
    const nyVal = getByPath(ny, path) ?? esVal

    let out
    if (code === 'es') out = esVal
    else if (code === 'ny') out = typeof nyVal === 'string' ? nyVal : esVal
    else {
      if (typeof esVal === 'string' && typeof nyVal === 'string' && esVal !== nyVal) {
        out = `${esVal} / ${nyVal}`
      } else {
        out = esVal
      }
    }

    if (out === undefined || typeof out !== 'string') {
      const tail = String(path).split('.').pop() || path
      const pretty = tail
        .replace(/_/g, ' ')
        .replace(/([a-z])([A-Z])/g, '$1 $2')
        .replace(/\s+/g, ' ')
        .trim()
      out = pretty || path
    }
    if (typeof out !== 'string') return path
    return out.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : ''))
  }
}

